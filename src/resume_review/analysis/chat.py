"""Bounded, evidence-scoped folder chat (PRD sections 9.1, 9.2, 9.4, 9.3).

Authority: PRD section 9 ("Folder-scoped chat and filtering"), especially
9.2 (query pipeline), 9.3 (proposed filter contract and action semantics) and
9.4 (context isolation), plus section 14 (fail closed) and 16.3 (human decision
boundaries).

This module is the whole chat pipeline for one reviewer question about one
folder. It performs five things, in this order, and nothing else:

1. **Binds the turn** to the authenticated reviewer through
   :meth:`~resume_review.db.repository_analysis.AnalysisRepositoryMixin.\
get_or_create_conversation`. The conversation id is generated by the helper, is
   opaque, and is the only identifier the model ever sees as a session reference;
   a candidate name, a filename or a folder path is never one (PRD 9.4).
2. **Retrieves a bounded slice of evidence** -- enough for the question, not every
   submission. Selection is deterministic application code (a query-term overlap
   over the current, non-stale profile of each in-scope document), capped by a
   hard :class:`ChatRetrievalBudget`. It is not a suitability score and never
   ranks applicants by quality: it only decides which evidence to place in front
   of the model.
3. **Returns a coverage object** stating how many in-scope submissions were
   actually inspected versus how many exist. A partial answer always carries that
   fact so the caller can surface it (PRD 9.4: "Do not answer an all-folder
   question from a partial context as though every submission was inspected.").
4. **Proposes, and stops.** A reviewer request that looks like an action ("move
   the rejects", "trash these") is turned into a structured :class:`ProposedAction`
   describing the intent and the implied document ids. No file is moved, no
   approval is recorded, and no batch is created (PRD 9.3: such a request creates
   an action plan, never an approval or an immediate move). A criterion the model
   proposes is recorded through ``create_criteria_proposal`` and stays unapproved
   until a human activates it; chat never activates a criteria version.
5. **Persists the exchange locally** through ``append_message``. History lives in
   the instance database, keyed by the opaque conversation id. There is no global
   or cross-job memory read or write anywhere on this path (PRD 9.4).

Two boundaries this module holds without exception:

* **Everything the model emits is untrusted data.** It is parsed into a fixed
  shape; a citation is accepted only if it resolves to evidence this turn actually
  retrieved; a criterion id is validated before it is stored; and nothing the
  model says is ever a SQL fragment, a shell string, a filesystem path or an
  authorization. The intent detector reads the *reviewer's question*, never the
  model's output, so a model cannot manufacture an action request.
* **The route fails closed.** :meth:`FolderChat.ask` refuses before any database
  write when its :class:`~resume_review.openclaw_adapter.policy.RoutePolicy` is
  unusable, and it never falls back to a second route. If the adapter raises, the
  exchange is not persisted and the question simply fails.
"""

