@dataclass(frozen=True)
class ChatRetrievalBudget:
    """Hard caps for one chat turn. Documented, bounded, and enforced.

    The budget is the mechanism behind PRD 9.4's "Do not stuff 400 full resumes
    into a prompt". Every field is a ceiling, never a target: the retriever fills
    up to the cap and stops.
    """

    #: Maximum number of submissions whose evidence may enter one prompt.
    max_documents: int = 8
    #: Maximum evidence rows taken from any single submission.
    max_evidence_per_document: int = 12
    #: Maximum characters of evidence text taken from any single submission.
    max_chars_per_document: int = 2_000
    #: Maximum characters of evidence text across the whole prompt.
    max_total_chars: int = 12_000
    #: Maximum distinct query terms distilled from the reviewer's question.
    max_query_terms: int = 12
    #: Maximum prior turns replayed from the stored conversation.
    max_history_messages: int = 12
    #: Maximum characters of prior-turn text replayed into the prompt.
    max_prior_chars: int = 8_000
    #: Maximum criteria the model may propose in one turn.
    max_criteria_proposals: int = 5

    def __post_init__(self) -> None:
        for name in (
            "max_documents",
            "max_evidence_per_document",
            "max_chars_per_document",
            "max_total_chars",
            "max_query_terms",
            "max_history_messages",
            "max_prior_chars",
            "max_criteria_proposals",
        ):
            if int(getattr(self, name)) < 1:
                raise InvalidInput(
                    "Every chat retrieval budget ceiling must be at least one.",
                    code=Code.INVALID_INPUT,
                    detail={"field": name},
                )

    def describe(self) -> dict[str, int]:
        return {k: int(v) for k, v in asdict(self).items()}


